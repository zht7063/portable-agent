import { chmod, mkdir, rename, writeFile } from 'node:fs/promises';
import { isAbsolute, join } from 'node:path';

/**
 * D4: the pa-key wrapper lives in the client's own directory (no PATH changes); harness configs reference its
 * absolute path. It runs the helper script with the app's bundled runtime (ELECTRON_RUN_AS_NODE=1), no Node install needed.
 */
export interface WrapperSpec { dir: string; execPath: string; scriptPath: string; platform?: NodeJS.Platform }

const shQuote = (s: string) => `'${s.replace(/'/g, `'\\''`)}'`;

export function wrapperFileName(platform: NodeJS.Platform = process.platform) { return platform === 'win32' ? 'pa-key.cmd' : 'pa-key'; }

export function renderWrapper(s: WrapperSpec): string {
  const platform = s.platform ?? process.platform;
  for (const p of [s.execPath, s.scriptPath]) if (!isAbsolute(p) && !/^[A-Za-z]:[\\/]/.test(p)) throw new Error('wrapper paths must be absolute');
  if (platform === 'win32') {
    for (const p of [s.execPath, s.scriptPath]) if (/["%^&|<>\r\n]/.test(p)) throw new Error('unsupported character in path');
    return `@echo off\r\nsetlocal\r\nset ELECTRON_RUN_AS_NODE=1\r\n"${s.execPath}" "${s.scriptPath}" %*\r\n`;
  }
  if (/[\r\n]/.test(s.execPath + s.scriptPath)) throw new Error('unsupported character in path');
  return `#!/bin/sh\n# Generated by Portable Agent. Prints a harness key from the OS keychain.\nELECTRON_RUN_AS_NODE=1 exec ${shQuote(s.execPath)} ${shQuote(s.scriptPath)} "$@"\n`;
}

/** Writes (atomically) the wrapper into `dir` and returns its absolute path. */
export async function installWrapper(s: WrapperSpec): Promise<string> {
  const platform = s.platform ?? process.platform;
  await mkdir(s.dir, { recursive: true, mode: 0o700 });
  const target = join(s.dir, wrapperFileName(platform));
  const tmp = `${target}.tmp-${process.pid}`;
  await writeFile(tmp, renderWrapper(s), { mode: 0o700 });
  await chmod(tmp, 0o700);
  await rename(tmp, target);
  return target;
}
